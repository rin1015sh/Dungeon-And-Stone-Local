def dress(t):
	"""거리 소품을 쓰임새 자리에(CT98): 길 · 광장 · 마당 위, 문 앞 · 길 가운데는 비운다."""
	import math
	# 가로등: 큰길 가장자리를 따라 9칸마다 번갈아
	for name in ("main", "main_s", "s1", "s5", "s7"):
		pts, sw = t.st[name]
		side = 1
		for (ax, az), (bx, bz) in zip(pts, pts[1:]):
			L = math.hypot(bx - ax, bz - az)
			ux, uz = (bx - ax) / L, (bz - az) / L
			k = 4.0
			while k < L - 1:
				for off in (sw / 2 - 0.55, sw / 2 - 0.9):
					if t.spot("lamp", ax + ux * k - uz * off * side, az + uz * k + ux * off * side, 0.8, 0.8):
						break
				side = -side
				k += 9.0
	# 광장: 우물 · 벤치 · 좌판(가운데 돌 단과 큰길 들머리는 비운다)
	if t.spot("well", -6.5, -19.5, 1.6, 1.6):
		t.mark(14, -6.5, -19.5)
	for x, z in ((-4.2, -15.6), (4.2, -15.6)):
		t.spot("bench", x, z, 2.0, 0.8)
	for x, z in ((6.4, -24.0), (6.6, -20.6)):
		t.spot("stall", x, z, 2.2, 1.2)
	# 노점 터: 좌판 넷 · 가운데 분수 · 상자
	for x, z in ((-12.3, -11.3), (-5.0, -11.3), (-12.3, -6.3), (-5.0, -6.3)):
		t.spot("stall", x, z, 2.2, 1.2)
	t.spot("fountain", -8.6, -8.8, 2.0, 2.0)
	t.spot("crate", -9.3, -11.6, 0.9, 0.9)
	# 시설 둘레: 가게 · 대장간 · 창고 · 선술집은 문 옆에 상자 · 통 · 수레, 여관 · 길드는 화분
	for h in t.p.houses:
		fid = h.get("facility", "")
		num = h.get("num", 0)
		if not fid and num not in (11, 13, 19, 21):
			continue
		(fx, fz), (w, d), yaw = h["front_c"], h["wd"], h["yaw"]
		ux, uz = math.cos(math.radians(yaw)), -math.sin(math.radians(yaw))
		nx, nz = math.sin(math.radians(yaw)), math.cos(math.radians(yaw))
		kinds = {"inn": ("planter", "planter"), "guild": ("planter", "planter"), "shop": ("crate", "barrel"), "smithy": ("barrel", "cart"),
				"bank": ("planter", "planter")}.get(fid, {11: ("barrel", "barrel"), 13: ("planter", "crate"), 19: ("crate", "crate"), 21: ("cart", "crate")}.get(num, ("crate", "barrel")))
		for sgn, kind in zip((-1, 1), kinds):
			for along in (w / 2 - 0.7, w / 2 - 1.6):
				x = fx + ux * along * sgn + nx * 0.75
				z = fz + uz * along * sgn + nz * 0.75
				ww = 1.8 if kind == "cart" else 0.9
				if t.spot(kind, x, z, ww, 0.9):
					break
	# 서문 앞 수레 · 다리 옆 통
	t.spot("cart", -31.5, -6.6, 1.8, 0.9)
	t.spot("barrel", -3.2, 20.6, 0.9, 0.9)
	# 뒷마당 빨랫줄: 집 뒤 넓은 흙마당에만
	n = 0
	for z in range(-66, 24, 3):
		for x in range(-36, 37, 3):
			if n >= 6:
				break
			i, j = int((z - tv.Z0) * tv.MS), int((x - tv.X0) * tv.MS)
			win = t.mask[max(0, i - 3):i + 4, max(0, j - 5):j + 6]
			if win.size and (win == 0).all() and t.spot("laundry", x, z, 2.4, 0.8):
				n += 1
