#!/usr/bin/env python3
"""2층 균열 「꺼진 태양의 신전」 설계도 지도 셋(plans/expansion_f1_3_B §4): data/maps/rifts/rift_sun_temple_ch1~3.json.
1층 균열 설계도와 같은 형식(rows · legend · marks). 강철의 묘 균열 타일(metal_* · it_* — 빛줄기 · 화로 · 석상)과 2층 모래(f2r_sand)를 빌려 쓴다.
짜는 법(덧대기 · 가장자리 길목 · 검사)은 rift_sunken_graveyard.py와 같다. 고칠 것은 아래 그림(글자 지도)만.

    python3 tools/rift_sun_temple.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rift_sunken_graveyard as base  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

LEGEND = {
    " ": "metal_wall", "#": "metal_wall", ".": "metal_floor", ",": "it_flagstone", ":": "it_rubble", "~": "f2r_sand",
    "l": "it_sunbeam", "O": "it_pillar", "S": "it_statue", "B": "it_brazier", "X": "it_debris", "o": "it_urn",
}
WALK = {".", ",", ":", "~", "l"}

# 1장 모래 묻힌 회랑 — 기둥이 늘어선 기울어진 회랑, 천장 틈으로 모래가 흘러내려 쌓였다. 끝 넓은 방에 오래된 돌 거인.
CH1 = r"""
##############################################################################################
##############################################################################################
#,,,,O,,,,O,,,,O,,,,O,,,,O,,,,O,,,,O,,,,O,,,,######################################.......####
#,,~~,,,,,,,,~~~,,,,,,,,,,~~~,,,,,,,,,,,,,,,,,######################################.........##
#,~~~~,,,,,,,~~~~,,,,,,,~~~~~,,,,,,,,,~~,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,.....~~~.....
#,,~~,,,,,,,,,~~,,,,,,,,,~~~,,,,,,,,,~~~~,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,....~~~~~....
#,,,,O,,,,O,,,,O,,,,O,,,,O,,,,O,,,,O,,,,O,,,,######################,,,############.....~~~.....
#######################################,,,,,#######################,,,############.........##
#######################################,,,,,#######################,,,############.......####
######################.....~~~~~.......,,,,,####################,,,,,,,,,#####################
######################..o...~~~~~...o..,,,,,####################,,,~~~,,,#####################
######################.....~~~~~.......,,,,,,,,,,,,,,,,,,,,,,,,,,,,~~~~~,,#####################
######################..o.....~~....o..,,,,,,,,,,,,,,,,,,,,,,,,,,,,,~~~,,,#####################
######################.................#############################,,,########################
##############################################################################################
"""
CH1_MARKS = {"entry": [1, 4], "exit": [93, 4], "slots": [[30, 4], [60, 11], [86, 5]],
             "posts": [[42, 8], [68, 9]], "loot": [[24, 10], [37, 12], [20, 3], [70, 10], [84, 3]],
             "hidden": [[29, 12]], "hazards": []}

# 2장 해시계 뜰 — 가운데 넓은 뜰, 천장 틈으로 빛줄기가 드는 칸(l), 거울 기둥 넷(S), 둘레 회랑.
CH2 = r"""
######################################################################
##############################.........###############################
#############.......................................##################
############....,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,....#################
###########....,,S,,,,,,,,,,,,,lll,,,,,,,,,,,,,S,,....###############
#..............,,,,,,,,,,,,,,,lllll,,,,,,,,,,,,,,,,.....#############
#..............,,,,,,,,,,,,,,lllllll,,,,,,,,,,,,,,,......###########.
#..............,,,,,,,,,,,,,,,lllll,,,,,,,,,,,,,,,,...................
#..............,,,,,,,,,,,,,,,,lll,,,,,,,,,,,,,,,,,.....#############.
###########....,,S,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,S,,....###############
############....,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,....#################
#############.......................................##################
##############################.........###############################
######################################################################
"""
CH2_MARKS = {"entry": [1, 7], "exit": [69, 7], "slots": [[24, 7], [52, 7]],
             "posts": [[33, 2], [33, 12]], "loot": [[14, 3], [14, 11], [46, 3], [46, 11], [60, 7]],
             "hidden": [[33, 7]], "hazards": []}

# 3장 지하 성소 — 둥근 성소, 둘레에 꺼진 화로 넷(B), 한가운데 거상.
CH3 = r"""
##################################################
#################..................###############
##############........................############
############....B..................B....##########
###########..............................#########
##########..........,,,,,,,,,,,..........#########
#.....................,,,,,,,,,,,,,.........######
#.....................,,,,,,,,,,,,,.........######
##########..........,,,,,,,,,,,..........#########
###########..............................#########
############....B..................B....##########
##############........................############
#################..................###############
##################################################
"""
CH3_MARKS = {"entry": [1, 7], "exit": [40, 7], "slots": [[12, 7], [37, 7]],
             "posts": [], "loot": [[20, 2], [20, 12], [36, 4]], "hidden": [[42, 6]], "hazards": []}

CHAPTERS = [("ch1", CH1, CH1_MARKS), ("ch2", CH2, CH2_MARKS), ("ch3", CH3, CH3_MARKS)]
PAD = {"ch1": (6, 6, 0, 0, "#"), "ch2": (8, 8, 0, 0, "#"), "ch3": (14, 14, 0, 0, "#")}
EDGE = {"ch1": {"exit": "right"}, "ch2": {"entry": "left", "exit": "right"}, "ch3": {"entry": "left"}}


def main():
    base.WALK.clear()
    base.WALK.update(WALK)
    for cid, art, marks in CHAPTERS:
        rows = base.carve(base.pad(base.rows_of(art), marks, PAD[cid]), marks, EDGE[cid])
        base.check(cid, rows, marks)
        d = {
            "_comment": "균열 챕터 설계도 — tools/rift_sun_temple.py가 만든다(손으로 고치지 말고 그 파일의 그림을 고친다). 형식은 1층 균열과 같다.",
            "rift": "rift_sun_temple", "chapter": cid, "width": len(rows[0]), "height": len(rows), "floor": "metal_floor",
            "legend": {k: v for k, v in LEGEND.items() if any(k in r for r in rows)}, "marks": marks, "rows": rows,
        }
        path = os.path.join(ROOT, "data", "maps", "rifts", "rift_sun_temple_%s.json" % cid)
        with open(path, "w", encoding="utf-8") as f:
            f.write(json.dumps(d, ensure_ascii=False, indent=1) + "\n")
        print("%s %dx%d = %d" % (cid, len(rows[0]), len(rows), len(rows[0]) * len(rows)))


if __name__ == "__main__":
    main()
